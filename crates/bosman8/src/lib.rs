//! Bosman-8 (DZM-180) machine core: Z80A @ 4 MHz, CPM-R in a 32 KB EPROM,
//! 8 × 32 KB banked RAM + 32 KB fixed RAM, Z80-SIO, 8253, WD1770, port 0x98.
//!
//! Pure logic: no threads, sockets or wall clock (so it can compile to WASM).
//! The application drives time with [`Bosman8::run_cycles`] and drains the
//! trace log / printer output. Serial channels are attached to
//! [`b8_link::Endpoint`]s (SIO-A = terminal, SIO-B = aux).
//!
//! See `doc/bosman8-hardware.md` for the hardware model and how it was derived.

use std::collections::HashMap;

use b8_chips::{DiskImage, Latch259, Pit8253, Sio, SioChannel, Wd1770, Wd1770Timing};
use b8_link::{Endpoint, LineParams, Parity, StopBits};
use iz80::{Cpu, Machine};

pub mod disk;
pub mod cpmfs;
mod control;

/// CPU clock.
pub const CPU_HZ: u32 = 4_000_000;
/// 8253 input clock.
pub const PIT_HZ: u32 = 2_000_000;
/// Size of the EPROM as dumped (27256). A 64 KB image (27512) is accepted
/// too: latch Q0 then selects its upper half (see `Bus::peek`).
pub const ROM_SIZE: usize = 0x8000;
/// Number of 32 KB RAM banks in 0000–7FFF.
pub const BANKS: usize = 8;
const BANK_SIZE: usize = 0x8000;
/// How often (in CPU cycles) the serial endpoints are polled.
const PUMP_CYCLES: u64 = 1000;
/// Receiver hold-off after the baud-rate clock of a SIO channel (8253
/// counter 1 = A, 2 = B) is written, in CPU cycles (3 ms). The ROM's line
/// (re)initialisation `SIOB_INIT` (0x1487) programs the counter, reads the
/// data register, waits 2 ms and reads it again — anything received in that
/// window is thrown away. On a real line the remote side cannot send at the
/// new speed before it has switched too (it runs the same routine, including
/// the 2 ms delay), but bytes arriving through TCP or a USB adapter lose their
/// spacing and may already be queued; without the hold-off the D/E/F link
/// loses the first byte after the switch to 19200 bit/s (rozkaz 60h).
/// See doc/bosman8-interlink.md.
const RX_RESYNC_CYCLES: u32 = CPU_HZ / 1000 * 3;
/// Cap of the trace log buffer (lines) between two `take_log` calls.
const LOG_CAP: usize = 100_000;

/// Port 0x98 bits generated by the hardware (not DIP switches).
pub mod p98 {
    /// 0 = WD1770 DRQ active (inverted DRQ).
    pub const NOT_DRQ: u8 = 0x01;
    /// 1 = selected floppy drive ready (disk present).
    pub const DRIVE_READY: u8 = 0x04;
    /// 1 = parallel (punch) device busy.
    pub const PUNCH_BUSY: u8 = 0x10;
    /// 1 = Centronics printer ready (not BUSY).
    pub const PRINTER_READY: u8 = 0x80;
    /// Bits taken from the configured DIP value.
    pub const DIP_MASK: u8 = 0x6A;
}

/// Machine configuration.
#[derive(Debug, Clone)]
pub struct Config {
    /// Static (jumper) bits of port 0x98 IN; only [`p98::DIP_MASK`] bits are used.
    pub dip: u8,
    /// Log I/O accesses (first `trace_io_limit` per port and direction).
    pub trace_io: bool,
    pub trace_io_limit: u32,
    /// Start instruction tracing when PC reaches this address.
    pub trace_cpu_from: Option<u16>,
    /// Maximum number of traced instructions.
    pub trace_cpu_limit: u64,
    /// Use short FDC mechanical delays (steps, spin-up).
    pub fast_fdc: bool,
    /// Report the printer as ready (bit 7 of port 0x98).
    pub printer_ready: bool,
    /// Log bytes sent and received on SIO-B (aux) with the emulated time.
    pub trace_aux: bool,
    /// Pass the line speed / format programmed into the SIO (8253 counter,
    /// WR4, WR5) to the endpoints, so a host serial port follows the guest
    /// (e.g. the 9600 → 20833 bit/s switch of the D/E/F link).
    pub follow_line_params: bool,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            dip: 0x40,
            trace_io: false,
            trace_io_limit: 16,
            trace_cpu_from: None,
            trace_cpu_limit: 200_000,
            fast_fdc: false,
            printer_ready: true,
            trace_aux: false,
            follow_line_params: true,
        }
    }
}

/// Memory, I/O devices and everything the CPU sees.
pub struct Bus {
    rom: Vec<u8>,
    banks: Vec<u8>,
    high: Vec<u8>,
    /// Main 74LS259 at 0x00–0x0F (bank select, ROM/RAM).
    pub latch: Latch259,
    /// Second 74LS259 at 0xF0–0xFF (floppy control, NMI enable).
    pub latch2: Latch259,
    pub sio: Sio,
    pub pit: Pit8253,
    pub fdc: Wd1770,
    dip: u8,
    printer_ready: bool,
    printer: Vec<u8>,
    trace_io: bool,
    trace_io_limit: u32,
    io_counts: HashMap<(bool, u8), u32>,
    log: Vec<String>,
    timing_dirty: bool,
    /// Asynchronous line parameters of SIO-A / SIO-B (None = sync mode or clock not running).
    line: [Option<LineParams>; 2],
}

impl Bus {
    fn bank(&self) -> usize {
        let l = &self.latch;
        (l.bit(6) as usize) | (l.bit(4) as usize) << 1 | (l.bit(5) as usize) << 2
    }

    fn log(&mut self, s: String) {
        if self.log.len() < LOG_CAP {
            self.log.push(s);
        }
    }

    fn trace(&mut self, out: bool, port: u8, value: u8, what: &str) {
        if !self.trace_io {
            return;
        }
        let n = self.io_counts.entry((out, port)).or_insert(0);
        *n += 1;
        if *n <= self.trace_io_limit {
            let more = if *n == self.trace_io_limit { " (further accesses not logged)" } else { "" };
            let dir = if out { "OUT" } else { "IN " };
            self.log(format!("io: {dir} {port:02X} = {value:02X}  {what}{more}"));
        }
    }

    fn port98_in(&self) -> u8 {
        let mut v = self.dip & p98::DIP_MASK;
        if !self.fdc.drq() {
            v |= p98::NOT_DRQ;
        }
        if let Some(d) = self.selected_drive() {
            if self.fdc.disk(d).is_some() {
                v |= p98::DRIVE_READY;
            }
        }
        if self.printer_ready {
            v |= p98::PRINTER_READY;
        }
        v
    }

    /// Drive selected by the second latch: Q7 → drive 0 (B:), Q4 → drive 1 (C:).
    fn selected_drive(&self) -> Option<usize> {
        if self.latch2.bit(7) {
            Some(0)
        } else if self.latch2.bit(4) {
            Some(1)
        } else {
            None
        }
    }

    fn update_fdc_select(&mut self) {
        let side = self.latch2.bit(3) as u8;
        let d = self.selected_drive();
        self.fdc.select(d, side);
    }

    /// NMI line level: WD1770 INTRQ gated by second latch Q1.
    fn nmi_level(&self) -> bool {
        self.fdc.intrq() && self.latch2.bit(1)
    }

    fn tick(&mut self, cycles: u32) {
        self.sio.tick(cycles);
        self.pit.tick(cycles);
        self.fdc.tick(cycles);
    }

    fn update_serial_timing(&mut self) {
        self.timing_dirty = false;
        let a = self.pit.output_hz(1);
        let b = self.pit.output_hz(2);
        set_char_timing(&mut self.sio.a, a);
        set_char_timing(&mut self.sio.b, b);
        self.line = [line_params(&self.sio.a, a), line_params(&self.sio.b, b)];
    }
}

/// CPU cycles per character from the channel's clock (8253 output) and mode.
fn set_char_timing(ch: &mut SioChannel, clock_hz: Option<f64>) {
    let Some(hz) = clock_hz.filter(|&h| h > 0.0) else { return };
    let data = ch.bits_per_char();
    let bits = if ch.sync_mode() {
        data
    } else {
        let wr4 = ch.wr(4);
        let parity = (wr4 & 1) as u32;
        // Stop bits: 01 = 1, 10 = 1.5 (rounded up), 11 = 2.
        let stop = match (wr4 >> 2) & 3 {
            1 => 1,
            _ => 2,
        };
        1 + data + parity + stop
    };
    let cycles = CPU_HZ as f64 * bits as f64 * ch.clock_divider() as f64 / hz;
    ch.set_char_cycles(cycles.round().max(1.0) as u32);
}

/// Asynchronous line parameters of a channel (None in sync modes).
fn line_params(ch: &SioChannel, clock_hz: Option<f64>) -> Option<LineParams> {
    let hz = clock_hz.filter(|&h| h > 0.0)?;
    if ch.sync_mode() {
        return None;
    }
    let wr4 = ch.wr(4);
    let baud = (hz / ch.clock_divider() as f64).round() as u32;
    Some(LineParams {
        baud: baud.max(1),
        data_bits: ch.bits_per_char() as u8,
        parity: match wr4 & 3 {
            1 => Parity::Odd,
            3 => Parity::Even,
            _ => Parity::None,
        },
        stop_bits: match (wr4 >> 2) & 3 {
            1 => StopBits::One,
            2 => StopBits::OnePointFive,
            _ => StopBits::Two,
        },
    })
}

impl Machine for Bus {
    fn peek(&mut self, address: u16) -> u8 {
        let a = address as usize;
        if a >= 0x8000 {
            self.high[a - 0x8000]
        } else if self.latch.bit(7) {
            self.banks[self.bank() * BANK_SIZE + a]
        } else if self.latch.bit(0) && self.rom.len() > ROM_SIZE {
            // Q0 = EPROM A15 (hypothesis): upper half of a 64 KB image.
            self.rom[ROM_SIZE + a]
        } else {
            self.rom[a]
        }
    }

    fn poke(&mut self, address: u16, value: u8) {
        let a = address as usize;
        if a >= 0x8000 {
            self.high[a - 0x8000] = value;
        } else {
            let i = self.bank() * BANK_SIZE + a;
            self.banks[i] = value;
        }
    }

    fn port_in(&mut self, address: u16) -> u8 {
        let port = address as u8;
        let (v, what): (u8, &str) = match port {
            0x80 => (self.sio.a.read_data(), "SIO-A data"),
            0x81 => (self.sio.b.read_data(), "SIO-B data"),
            0x82 => (self.sio.a.read_ctrl(), "SIO-A status"),
            0x83 => (self.sio.b.read_ctrl(), "SIO-B status"),
            0x84..=0x87 => (self.pit.read(port & 3), "8253"),
            0x88..=0x8B => (self.fdc.read(port & 3), "WD1770"),
            0x98 => (self.port98_in(), "port 98 (DIP/status)"),
            0x9C => (0xFF, "port 9C (parallel input) - unemulated"),
            _ => (0xFF, "unknown"),
        };
        // Don't flood with polling of status registers unless asked for.
        self.trace(false, port, v, what);
        v
    }

    fn port_out(&mut self, address: u16, value: u8) {
        let port = address as u8;
        let what: String = match port {
            0x00..=0x0F => {
                let old = self.latch.value;
                self.latch.write(port);
                if (old ^ self.latch.value) & 0x01 != 0 && self.trace_io {
                    self.log(format!("io: latch Q0 := {} (EPROM upper half select?)", port & 1));
                }
                format!("latch Q{} := {} (bank {}, {})", (port >> 1) & 7, port & 1, self.bank(),
                    if self.latch.bit(7) { "RAM" } else { "ROM" })
            }
            0x80 => {
                self.sio.a.write_data(value);
                "SIO-A data".into()
            }
            0x81 => {
                self.sio.b.write_data(value);
                "SIO-B data".into()
            }
            0x82 => {
                self.sio.a.write_ctrl(value);
                self.timing_dirty = true;
                "SIO-A ctrl".into()
            }
            0x83 => {
                self.sio.b.write_ctrl(value);
                self.timing_dirty = true;
                "SIO-B ctrl".into()
            }
            0x84..=0x87 => {
                self.pit.write(port & 3, value);
                self.timing_dirty = true;
                match port {
                    0x85 => self.sio.a.hold_rx(RX_RESYNC_CYCLES),
                    0x86 => self.sio.b.hold_rx(RX_RESYNC_CYCLES),
                    _ => {}
                }
                "8253".into()
            }
            0x88..=0x8B => {
                self.fdc.write(port & 3, value);
                "WD1770".into()
            }
            0x98 => {
                self.printer.push(value);
                "Centronics data".into()
            }
            0xF0..=0xFF => {
                self.latch2.write(port);
                self.update_fdc_select();
                let bit = (port >> 1) & 7;
                let name = match bit {
                    1 => "NMI (INTRQ) enable",
                    2 => "FDC reset? (pulsed low on timeout)",
                    3 => "side select",
                    4 => "drive 1 (C:) select",
                    7 => "drive 0 (B:) select",
                    _ => "unknown",
                };
                format!("latch2 Q{bit} := {} ({name})", port & 1)
            }
            _ => "unknown".into(),
        };
        self.trace(true, port, value, &what);
    }
}

/// The Bosman-8 machine.
pub struct Bosman8 {
    cpu: Cpu,
    pub bus: Bus,
    term: Box<dyn Endpoint>,
    aux: Box<dyn Endpoint>,
    nmi_prev: bool,
    cycles: u64,
    next_pump: u64,
    tx_break: [bool; 2],
    /// Line parameters last passed to the term / aux endpoint.
    line_applied: [Option<LineParams>; 2],
    follow_line_params: bool,
    trace_cpu_from: Option<u16>,
    trace_cpu_left: u64,
    tracing_cpu: bool,
    trace_aux: bool,
}

impl Bosman8 {
    /// Create a machine. `rom` is 32 KB, or 64 KB with a second half selected
    /// by latch Q0 (shorter images are padded with 0xFF).
    pub fn new(rom: &[u8], config: Config, term: Box<dyn Endpoint>, aux: Box<dyn Endpoint>) -> Self {
        let mut r = rom.to_vec();
        r.resize(if rom.len() > ROM_SIZE { 2 * ROM_SIZE } else { ROM_SIZE }, 0xFF);
        let mut fdc = Wd1770::new(CPU_HZ);
        if config.fast_fdc {
            fdc.set_timing(Wd1770Timing::fast());
        }
        let bus = Bus {
            rom: r,
            banks: vec![0; BANKS * BANK_SIZE],
            high: vec![0; 0x8000],
            latch: Latch259::new(),
            latch2: Latch259::new(),
            sio: Sio::new(),
            pit: Pit8253::new(PIT_HZ, CPU_HZ),
            fdc,
            dip: config.dip,
            printer_ready: config.printer_ready,
            printer: Vec::new(),
            trace_io: config.trace_io,
            trace_io_limit: config.trace_io_limit,
            io_counts: HashMap::new(),
            log: Vec::new(),
            timing_dirty: true,
            line: [None; 2],
        };
        Self {
            cpu: Cpu::new_z80(),
            bus,
            term,
            aux,
            nmi_prev: false,
            cycles: 0,
            next_pump: 0,
            tx_break: [false; 2],
            line_applied: [None; 2],
            follow_line_params: config.follow_line_params,
            trace_cpu_from: config.trace_cpu_from,
            trace_cpu_left: config.trace_cpu_limit,
            tracing_cpu: false,
            trace_aux: config.trace_aux,
        }
    }

    /// Total CPU cycles executed.
    pub fn cycles(&self) -> u64 {
        self.cycles
    }

    pub fn pc(&self) -> u16 {
        self.cpu.immutable_registers().pc()
    }

    /// Read memory as the CPU currently sees it.
    pub fn peek(&mut self, addr: u16) -> u8 {
        self.bus.peek(addr)
    }

    /// Insert (or remove) a floppy: drive 0 = B:, drive 1 = C:.
    pub fn insert_disk(&mut self, drive: usize, disk: Option<DiskImage>) {
        self.bus.fdc.insert(drive, disk);
    }

    pub fn disk(&self, drive: usize) -> Option<&DiskImage> {
        self.bus.fdc.disk(drive)
    }

    pub fn term_describe(&self) -> String {
        self.term.describe()
    }

    pub fn aux_describe(&self) -> String {
        self.aux.describe()
    }

    /// Drain the trace log.
    pub fn take_log(&mut self) -> Vec<String> {
        std::mem::take(&mut self.bus.log)
    }

    /// Drain bytes sent to the Centronics port.
    pub fn take_printer(&mut self) -> Vec<u8> {
        std::mem::take(&mut self.bus.printer)
    }

    /// Run for at least `n` CPU cycles.
    pub fn run_cycles(&mut self, n: u64) {
        let target = self.cycles + n;
        while self.cycles < target {
            self.step();
        }
        self.pump();
    }

    /// Execute one instruction (or 4 idle cycles while halted).
    pub fn step(&mut self) {
        if let Some(a) = self.trace_cpu_from {
            if !self.tracing_cpu && self.pc() == a {
                self.tracing_cpu = true;
            }
        }
        if self.tracing_cpu && self.trace_cpu_left > 0 {
            self.trace_instruction();
        }
        let before = self.cpu.cycle_count();
        self.cpu.execute_instruction(&mut self.bus);
        let mut d = self.cpu.cycle_count().wrapping_sub(before);
        if d == 0 {
            d = 4; // halted: time still passes
        }
        self.bus.tick(d as u32);
        if self.bus.timing_dirty {
            self.bus.update_serial_timing();
        }
        let nmi = self.bus.nmi_level();
        if nmi && !self.nmi_prev {
            self.cpu.signal_nmi();
        }
        self.nmi_prev = nmi;
        self.cycles += d;
        if self.cycles >= self.next_pump {
            self.next_pump = self.cycles + PUMP_CYCLES;
            self.pump();
        }
    }

    fn trace_instruction(&mut self) {
        self.trace_cpu_left -= 1;
        let pc = self.pc();
        let text = self.cpu.disasm_instruction(&mut self.bus);
        self.cpu.registers().set_pc(pc);
        let r = self.cpu.immutable_registers();
        use iz80::Reg16::*;
        let line = format!(
            "cpu: {pc:04X}  {text:<20} AF={:04X} BC={:04X} DE={:04X} HL={:04X} IX={:04X} IY={:04X} SP={:04X} bank={}{}",
            r.get16(AF), r.get16(BC), r.get16(DE), r.get16(HL), r.get16(IX), r.get16(IY), r.get16(SP),
            self.bus.bank(), if self.bus.latch.bit(7) { "" } else { " ROM" },
        );
        self.bus.log(line);
    }

    /// Move bytes between the SIO channels and the endpoints.
    fn pump(&mut self) {
        let lines = self.bus.line;
        let mut line_log = Vec::new();
        let chans: [(&mut SioChannel, &mut Box<dyn Endpoint>); 2] =
            [(&mut self.bus.sio.a, &mut self.term), (&mut self.bus.sio.b, &mut self.aux)];
        let mut sent = Vec::new();
        let mut received = Vec::new();
        let mut dropped = Vec::new();
        for (i, (ch, ep)) in chans.into_iter().enumerate() {
            let aux = i == 1 && self.trace_aux;
            // Bytes carry their emulated time so a host serial port can keep
            // their spacing on the wire (the emulator runs in time slices).
            let now = self.cycles as f64 / CPU_HZ as f64;
            while let Some(b) = ch.take_tx() {
                ep.write_at(b, now);
                if aux {
                    sent.push(b);
                }
            }
            // Speed / format change after the bytes sent at the old setting.
            let line = lines[i];
            if self.follow_line_params && line.is_some() && line != self.line_applied[i] {
                let p = line.expect("checked");
                ep.set_line_params_at(p, now);
                self.line_applied[i] = line;
                if aux || (i == 0 && self.trace_aux) {
                    line_log.push(format!("{} {now:11.6} line {p}", if i == 0 { "term" } else { "aux" }));
                }
            }
            let brk = ch.break_active();
            if brk && !self.tx_break[i] {
                ep.send_break();
            }
            self.tx_break[i] = brk;
            // SIO-B: what arrives while the receiver is disabled (before the ROM
            // opened the line) is lost, as on the real chip — otherwise e.g. the
            // slave's greeting sent when it entered DEBUG would be read later as
            // a reply and shift the D/E/F protocol. (The terminal channel keeps
            // such bytes: type-ahead during boot is harmless and convenient.)
            if i == 1 && !ch.rx_enabled() {
                while let Some(b) = ep.read() {
                    if aux {
                        dropped.push(b);
                    }
                }
            }
            // Don't let the host queue grow without bound if the guest is not reading.
            while ch.rx_pending() < 4096 {
                match ep.read() {
                    Some(b) => {
                        ch.push_rx(b);
                        if aux {
                            received.push(b);
                        }
                    }
                    None => break,
                }
            }
        }
        for l in line_log {
            self.bus.log(l);
        }
        if self.trace_aux {
            let t = self.cycles as f64 / CPU_HZ as f64;
            for (dir, bytes) in [("->", sent), ("<-", received), ("<- (Rx disabled, lost)", dropped)] {
                if !bytes.is_empty() {
                    let hex: Vec<String> = bytes.iter().map(|b| format!("{b:02X}")).collect();
                    self.bus.log(format!("aux {t:11.6} {dir} {}", hex.join(" ")));
                }
            }
        }
    }
}
